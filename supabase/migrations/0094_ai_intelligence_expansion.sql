ALTER TABLE conversation_context ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_recommendations ENABLE ROW LEVEL SECURITY;
ALTER TABLE clarification_intelligence ENABLE ROW LEVEL SECURITY;
ALTER TABLE evidence_extractions ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_metrics ENABLE ROW LEVEL SECURITY;

-- Standard Project Scope Policies
CREATE POLICY "Project team can view ai_memory"
    ON ai_memory FOR SELECT
    USING (project_id IN (SELECT project_id FROM project_users WHERE user_id = auth.uid()));

CREATE POLICY "Project team can view ai_memory_events"
    ON ai_memory_events FOR SELECT
    USING (project_id IN (SELECT project_id FROM project_users WHERE user_id = auth.uid()));

CREATE POLICY "Users can manage their conversation_context"
    ON conversation_context FOR ALL
    USING (user_id = auth.uid());

CREATE POLICY "Project team can view ai_recommendations"
    ON ai_recommendations FOR SELECT
    USING (project_id IN (SELECT project_id FROM project_users WHERE user_id = auth.uid()));

CREATE POLICY "Project team can view clarification_intelligence"
    ON clarification_intelligence FOR SELECT
    USING (project_id IN (SELECT project_id FROM project_users WHERE user_id = auth.uid()));

CREATE POLICY "Project team can view evidence_extractions"
    ON evidence_extractions FOR SELECT
    USING (project_id IN (SELECT project_id FROM project_users WHERE user_id = auth.uid()));

CREATE POLICY "Admins can view ai_metrics"
    ON ai_metrics FOR SELECT
    USING (true); -- Usually restricted, keeping open for MVP tracking

-- Indexes
CREATE INDEX idx_ai_memory_project ON ai_memory(project_id);
CREATE INDEX idx_ai_recommendations_project_credit ON ai_recommendations(project_id, credit_id);
CREATE INDEX idx_evidence_extractions_document ON evidence_extractions(document_id);
CREATE INDEX idx_conversation_context_user_session ON conversation_context(user_id, session_id);
